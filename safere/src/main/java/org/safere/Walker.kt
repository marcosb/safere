package org.safere

import java.util.*

/**
 * Non-recursive tree walker for [Regexp] ASTs. Uses an explicit stack to avoid stack overflow
 * on deeply nested expressions.
 * 
 * 
 * Subclasses override [.preVisit], [.postVisit], [.copy], and [ ][.shortVisit] to define the traversal behavior. The walker calls `preVisit` before visiting
 * a node's children and `postVisit` after all children have been visited.
 * 
 * 
 * This is a port of RE2's `walker-inl.h`.
 * 
 * @param <T> the type of value accumulated during the walk
</T> */
internal abstract class Walker<T> {
    private val stack = ArrayList<WalkState<T?>>()
    private val stop = BooleanArray(1)
    private var stoppedEarly = false
    private var maxVisits = 0

    /**
     * Called before visiting `re`'s children.
     * 
     * 
     * The returned value is passed to `postVisit` as `preArg` and to children's `preVisit` and `postVisit` as `parentArg`.
     * 
     * 
     * If this method sets `stop[0]` to true, the walk does not recurse into children and the
     * return value is used as the result for this node (as if it were the `postVisit` result).
     * 
     * @param re the node being visited
     * @param parentArg the accumulated argument from the parent (or `topArg` for the root)
     * @param stop single-element array; set `stop[0] = true` to skip children
     * @return the value to pass to children and to postVisit
     */
    protected open fun preVisit(re: Regexp, parentArg: T?, stop: BooleanArray): T? {
        return parentArg
    }

    /**
     * Called after visiting `re`'s children.
     * 
     * @param re the node being visited
     * @param parentArg the accumulated argument from the parent
     * @param preArg the value returned by preVisit
     * @param childArgs list of values returned by children's postVisit. Empty if there are no
     * children. Mutable — implementations may modify it (e.g., for coalescing).
     * @return the result for this node
     */
    protected open fun postVisit(re: Regexp, parentArg: T?, preArg: T?, childArgs: MutableList<T>): T? {
        return preArg
    }

    /**
     * Called to copy a value when the walker notices that adjacent children are the same Regexp
     * object. Only used in [.walk], not in [.walkExponential].
     */
    protected open fun copy(arg: T?): T? {
        return arg
    }

    /**
     * Called to do a quick visit of a node (but not its children) when the visit budget has been
     * exhausted. Should return a value that makes sense for the remaining parent postVisits.
     */
    protected abstract fun shortVisit(re: Regexp, parentArg: T?): T?

    /** Returns how many copies of a counted operand to visit; structural analyses need only one.  */
    protected open fun repeatVisits(re: Regexp?): Int {
        return 1
    }

    /** Returns true if the walk was cut short due to the visit budget being exhausted.  */
    fun stoppedEarly(): Boolean {
        return stoppedEarly
    }

    /**
     * Walks over a regular expression tree, using [.copy] to avoid re-visiting shared
     * sub-trees.
     */
    fun walk(re: Regexp?, topArg: T?): T? {
        maxVisits = 1000000
        return walkInternal(re, topArg, true)
    }

    /**
     * Walks over a regular expression tree without using [.copy]. This can lead to exponential
     * runtimes on cross-linked Regexps (like those generated by Simplify). At most `maxVisits`
     * nodes will be visited; after that, [.shortVisit] is called instead.
     */
    fun walkExponential(re: Regexp?, topArg: T?, maxVisits: Int): T? {
        this.maxVisits = maxVisits
        return walkInternal(re, topArg, false)
    }

    private fun walkInternal(re: Regexp?, topArg: T?, useCopy: Boolean): T? {
        stoppedEarly = false
        stack.clear()

        if (re == null) {
            return topArg
        }

        stack.add(WalkState<T?>(re, topArg))

        while (true) {
            val s = stack[stack.size - 1]
            val cur = s.re!!
            // Keep ordinary child traversal direct: most walkers never expand counted operands.
            val nsub = if (cur.op == RegexpOp.REPEAT) repeatVisits(cur) else if (cur.subs == null) 0 else cur.subs!!.size

            if (s.n == -1) {
                // Need to call preVisit.
                if (--maxVisits < 0) {
                    stoppedEarly = true
                    val t = shortVisit(cur, s.parentArg)
                    stack.removeAt(stack.size - 1)
                    if (stack.size == 0) {
                        return t
                    }
                    val parent = stack[stack.size - 1]
                    parent.childArgs.add(t)
                    parent.n++
                    continue
                }
                stop[0] = false
                s.preArg = preVisit(cur, s.parentArg, stop)
                if (stop[0]) {
                    val t = s.preArg
                    stack.removeAt(stack.size - 1)
                    if (stack.size == 0) {
                        return t
                    }
                    val parent = stack[stack.size - 1]
                    parent.childArgs.add(t)
                    parent.n++
                    continue
                }
                s.n = 0
                s.childArgs = ArrayList<T?>(nsub)
                // Fall through to child processing.
            }

            // Process children.
            if (nsub > 0 && s.n < nsub) {
                if (useCopy
                    && s.n > 0
                    && (cur.op == RegexpOp.REPEAT || cur.subs!![s.n - 1] === cur.subs!![s.n])
                ) {
                    val prev = s.childArgs[s.n - 1]
                    s.childArgs.add(copy(prev))
                    s.n++
                    continue
                }
                stack.add(WalkState<T?>(cur.subs!![if (cur.op == RegexpOp.REPEAT) 0 else s.n], s.preArg))
                continue
            }

            // All children done (or no children). Call postVisit.
            val t = postVisit(cur, s.parentArg, s.preArg, s.childArgs as MutableList<T>)
            stack.removeAt(stack.size - 1)
            if (stack.size == 0) {
                return t
            }
            val parent = stack[stack.size - 1]
            parent.childArgs.add(t)
            parent.n++
        }
    }

    /** State for a single level in the traversal.  */
    private class WalkState<T>(val re: Regexp?, val parentArg: T?) {
        var n: Int = -1 // -1 means need preVisit; >= 0 is index of next child to process
        var preArg: T? = null
        var childArgs: MutableList<T?> = Collections.emptyList<T?>()
    }
}
